"""Database models for chart vision analyses."""

from django.db import models

from subscriptions.models import BotUser


class BybitKline(models.Model):
    symbol = models.CharField(max_length=20)
    interval = models.CharField(max_length=10)
    open_time = models.DateTimeField()
    open_price = models.DecimalField(max_digits=24, decimal_places=10)
    high_price = models.DecimalField(max_digits=24, decimal_places=10)
    low_price = models.DecimalField(max_digits=24, decimal_places=10)
    close_price = models.DecimalField(max_digits=24, decimal_places=10)
    volume = models.DecimalField(max_digits=32, decimal_places=10, null=True, blank=True)
    turnover = models.DecimalField(max_digits=32, decimal_places=10, null=True, blank=True)
    source = models.CharField(max_length=20, default="bybit")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ("symbol", "interval", "open_time")
        indexes = [
            models.Index(fields=["symbol", "interval", "open_time"]),
        ]
        ordering = ["symbol", "interval", "open_time"]

    def __str__(self):
        open_time = self.open_time.strftime("%Y-%m-%d %H:%M:%S")
        return f"{self.symbol} {self.interval} {open_time}"


class ChartVisionResult(models.Model):
    SOURCE_GENERATED = "generated"
    SOURCE_SCREENSHOT = "screenshot"

    SOURCE_CHOICES = [
        (SOURCE_GENERATED, "Generated Bybit-style chart"),
        (SOURCE_SCREENSHOT, "Real Bybit screenshot"),
    ]

    user = models.ForeignKey(
        BotUser,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="chart_vision_results",
    )
    symbol = models.CharField(max_length=20, null=True, blank=True)
    interval = models.CharField(max_length=10, default="D")
    source = models.CharField(max_length=20, choices=SOURCE_CHOICES)
    image = models.ImageField(upload_to="chart_vision/")
    predicted_label = models.CharField(max_length=20)
    confidence = models.FloatField()
    probability_uptrend = models.FloatField(null=True, blank=True)
    probability_downtrend = models.FloatField(null=True, blank=True)
    probability_sideways = models.FloatField(null=True, blank=True)
    model_version = models.CharField(max_length=50, default="chart_resnet18_v1")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        symbol = self.symbol or "unknown"
        return f"{symbol} {self.interval} {self.predicted_label} {self.confidence:.2f}"
